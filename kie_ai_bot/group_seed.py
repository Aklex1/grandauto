# --- Состояние -------------------------------------------------------------

def _db_path() -> str:
    return os.getenv("NEWS_DB", "/opt/kie_ai_bot/news.db")


def _connect() -> sqlite3.Connection:
    conn = sqlite3.connect(_db_path(), timeout=30)
    conn.row_factory = sqlite3.Row
    return conn


def init_db() -> None:
    with _connect() as conn:
        conn.execute("""
            CREATE TABLE IF NOT EXISTS seed_posts (
                key TEXT PRIMARY KEY,
                published_at TEXT NOT NULL,
                message_id INTEGER
            )
        """)
        conn.execute("""
            CREATE TABLE IF NOT EXISTS seed_state (
                name TEXT PRIMARY KEY,
                value TEXT NOT NULL
            )
        """)


def started_at() -> datetime:
    """
    Начало серии. Первый запуск задаёт отсчёт пяти дней.

    Привязываемся не к моменту запуска, а к часу первого поста: иначе
    бот, обновлённый в полночь, высыпал бы ночью все посты, которым «уже
    пора». Если этот час на сегодня прошёл, отсчёт начинается завтра, а
    первый пост всё равно выходит сразу — чтобы было видно, что серия
    пошла.
    """
    with _connect() as conn:
        row = conn.execute("SELECT value FROM seed_state WHERE name = 'started_at'").fetchone()
        if row:
            return datetime.fromisoformat(row["value"])

        tz = timezone(timedelta(hours=TZ_OFFSET))
        local = datetime.now(timezone.utc).astimezone(tz)
        hour, minute = (int(x) for x in POSTS[0][1].split(":"))
        anchor = local.replace(hour=hour, minute=minute, second=0, microsecond=0)
        if anchor < local - timedelta(minutes=30):
            anchor += timedelta(days=1)
        anchor = anchor.astimezone(timezone.utc)
        conn.execute("INSERT INTO seed_state (name, value) VALUES ('started_at', ?)", (anchor.isoformat(),))
        return anchor


def published() -> set:
    with _connect() as conn:
        return {r["key"] for r in conn.execute("SELECT key FROM seed_posts")}


def remember(key: str, message_id: Optional[int]) -> None:
    with _connect() as conn:
        conn.execute(
            "INSERT OR REPLACE INTO seed_posts (key, published_at, message_id) VALUES (?, ?, ?)",
            (key, datetime.now(timezone.utc).isoformat(), message_id),
        )


# --- Расписание ------------------------------------------------------------

def due_at(start: datetime, day: int, clock: str) -> datetime:
    """Время поста: день от начала серии плюс час из плана."""
    hour, minute = (int(x) for x in clock.split(":"))
    tz = timezone(timedelta(hours=TZ_OFFSET))
    local_start = start.astimezone(tz)
    day_start = local_start.replace(hour=hour, minute=minute, second=0, microsecond=0)
    return (day_start + timedelta(days=day)).astimezone(timezone.utc)


def next_post(start: datetime, now: datetime, done: set):
    """Ближайший неопубликованный пост, которому пора выходить."""
    for day, clock, key, text in POSTS:
        if key in done:
            continue
        when = due_at(start, day, clock)
        if when <= now:
            return key, text, when
        # План идёт по возрастанию: если этому ещё рано, следующим и подавно.
        return None
    return None


# --- Публикация ------------------------------------------------------------

async def publish_due(bot: Bot, force_first: bool = False) -> bool:
    start = started_at()
    now = datetime.now(timezone.utc)
    done = published()
    item = next_post(start, now, done)
    if not item and force_first and not done:
        # Самый первый пост выпускаем сразу после запуска: иначе при
        # отсчёте «с завтрашнего утра» сутки непонятно, работает ли оно.
        day, clock, key, text = POSTS[0]
        item = (key, text, now)
    if not item:
        return False
    key, text, when = item
    try:
        sent = await bot.send_message(
            CHAT_ID, text, message_thread_id=THREAD_ID or None,
            parse_mode="HTML", disable_web_page_preview=True,
        )
        remember(key, getattr(sent, "message_id", None))
        logger.info("[серия] опубликовано «%s» (по плану %s)", key, when.isoformat())
        return True
    except Exception as e:
        logger.error("[серия] не отправить «%s»: %s", key, e)
        # Помечаем только удачные: иначе один сбой съел бы пост навсегда.
        return False


async def seed_worker(bot: Bot) -> None:
    """Фоновый цикл: раз в SEED_TICK секунд смотрит, не пора ли публиковать."""
    if not ENABLED:
        logger.info("[серия] выключена (SEED_ENABLED=0)")
        return
    if not CHAT_ID:
        logger.error("[серия] не задан SEED_CHAT_ID — публиковать некуда")
        return

    init_db()
    start = started_at()
    done = len(published())
    logger.info("[серия] запущена: чат %s, тема %s, постов %s, уже вышло %s, отсчёт с %s",
                CHAT_ID, THREAD_ID, len(POSTS), done, start.isoformat())

    first = True
    while True:
        try:
            # За один проход — один пост: пачка сообщений подряд читается
            # как рассылка, а не как живая лента.
            await publish_due(bot, force_first=first)
            first = False
        except Exception as e:
            logger.error("[серия] ошибка: %s", e, exc_info=True)
        await asyncio.sleep(TICK)
