# --- Категория в WP --------------------------------------------------------

def _auth_header() -> dict:
    token = base64.b64encode(f"{BLOG_USER}:{APP_PASSWORD}".encode()).decode()
    return {"Authorization": f"Basic {token}"}


async def _ensure_category(client: httpx.AsyncClient) -> Optional[int]:
    """Возвращает id рубрики для статей, создаёт её при необходимости."""
    if CATEGORY_ID:
        return CATEGORY_ID
    try:
        resp = await client.get(f"{SITE_URL}/wp-json/wp/v2/categories",
                                params={"search": CATEGORY_NAME, "_fields": "id,name"},
                                headers=_auth_header(), timeout=25)
        for cat in resp.json() or []:
            if cat.get("name", "").lower() == CATEGORY_NAME.lower():
                return int(cat["id"])
        created = await client.post(f"{SITE_URL}/wp-json/wp/v2/categories",
                                    json={"name": CATEGORY_NAME},
                                    headers=_auth_header(), timeout=25)
        if created.status_code in (200, 201):
            return int(created.json()["id"])
    except Exception as e:
        logger.warning("[блог] рубрику не создать (%s), публикуем без неё", e)
    return None


async def publish_article(title: str, summary: str) -> Optional[str]:
    """Публикует статью в блог и возвращает её адрес. None — если не вышло."""
    if not enabled():
        logger.info("[блог] пропуск: не задан WP_APP_PASSWORD")
        return None

    article_title, content, excerpt = build_article(title, summary)

    try:
        async with httpx.AsyncClient(timeout=40, follow_redirects=True) as client:
            payload = {
                "title": article_title,
                "content": content,
                "excerpt": excerpt,
                "status": "publish",
            }
            category_id = await _ensure_category(client)
            if category_id:
                payload["categories"] = [category_id]

            resp = await client.post(f"{SITE_URL}/wp-json/wp/v2/posts",
                                     json=payload, headers=_auth_header())
            if resp.status_code in (200, 201):
                link = resp.json().get("link")
                logger.info("[блог] статья опубликована: %s", link)
                return link
            logger.error("[блог] публикация отклонена: %s %.200s",
                         resp.status_code, resp.text)
    except Exception as e:
        logger.error("[блог] публикация не удалась: %s", e)
    return None
