raw = io.open(SRC, encoding='utf-16').read()
lines = raw.splitlines()
head = lines[:3]
hdr = lines[2].split('\t')
rows = [l.split('\t') for l in lines[3:] if l.strip()]
width = len(hdr)

auto = [r for r in rows if r[13].strip() == '---autotargeting']
phrases = [r[13] for r in rows if r[13].strip() != '---autotargeting']

groups = collections.OrderedDict((k, []) for k, _, _ in RUB)
groups['obshchie'] = []
for ph in phrases:
    low = ' ' + ph.lower() + ' '
    hit = next((k for k, _, ws in RUB if any(w in low for w in ws)), None)
    groups[hit or 'obshchie'].append(ph)

sample = rows[0]
out = []
num = 1
for key, ks in groups.items():
    if not ks:
        continue
    num += 1
    url = (BASE if key == 'obshchie' else BASE + 'rubrika/' + key + '/') + TAIL
    titles, texts = COPY[key]
    first = True
    for ph in ks + ['---autotargeting']:
        r = [''] * width
        r[0] = ' -'                      # Доп. объявление группы
        r[1] = 'Комбинаторное'
        r[2] = 'search'
        r[3] = ' -'                      # Мобильное объявление
        r[4] = ''                        # ID группы — новая
        r[5] = TITLE[key]
        r[6] = str(num)
        r[7] = 'Единая перфоманс-кампания'
        r[8] = sample[8]                 # ID кампании (локальный)
        r[9] = sample[9]                 # ID кампании (серверный)
        r[10] = sample[10]
        r[11] = 'RUB'
        r[12] = ''                       # ID фразы — новая
        r[13] = ph
        r[14] = ''                       # ID объявления — новое
        if first:
            for i, t in enumerate(titles[:7]):
                r[18 + i] = t
            for i, t in enumerate(texts[:3]):
                r[25 + i] = t
            r[40] = url
            r[41] = SHOW[key]
            r[43] = 'Россия'
            r[61] = '16'
            first = False
        out.append(r)

bad = []
for r in out:
    for i in range(18, 25):
        if r[i] and len(r[i]) > 56:
            bad.append(('заголовок', len(r[i]), r[i]))
    for i in range(25, 28):
        if r[i] and len(r[i]) > 81:
            bad.append(('текст', len(r[i]), r[i]))
    if len(r) != width:
        bad.append(('ширина', len(r), ''))
    if r[41] and len(r[41]) > 20:
        bad.append(('отображаемая ссылка', len(r[41]), r[41]))
if bad:
    for b in bad:
        print('ПРЕВЫШЕНИЕ', b)
    raise SystemExit(1)

body = head + ['\t'.join(r) for r in out]
io.open(DST, 'w', encoding='utf-16', newline='').write('\r\n'.join(body) + '\r\n')
print('групп: %d, строк: %d' % (num - 1, len(out)))
