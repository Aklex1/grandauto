    public static function ensure_pages() {
        foreach (self::all() as $id => $page) {
            $option = self::option_key($id);
            $page_id = (int) get_option($option);
            $shortcode = '[genius_gift id="' . $id . '"]';

            if ($page_id <= 0) {
                $existing = get_page_by_path($page['slug']);
                if ($existing instanceof WP_Post) {
                    $page_id = (int) $existing->ID;
                }
            }
            if ($page_id > 0) {
                wp_update_post(array(
                    'ID'           => $page_id,
                    'post_title'   => $page['seo_title'],
                    'post_content' => $shortcode,
                    'post_status'  => 'publish',
                ));
            } else {
                $page_id = (int) wp_insert_post(array(
                    'post_title'   => $page['seo_title'],
                    'post_content' => $shortcode,
                    'post_status'  => 'publish',
                    'post_type'    => 'page',
                    'post_name'    => $page['slug'],
                ));
            }
            if ($page_id > 0) {
                update_option($option, $page_id, false);
            }
        }
    }

    public static function get_url($id) {
        $page_id = (int) get_option(self::option_key($id));
        if ($page_id > 0) {
            $link = get_permalink($page_id);
            if ($link) {
                return $link;
            }
        }
        $page = self::get($id);
        return home_url('/' . ($page ? $page['slug'] : '') . '/');
    }

    /** Страница подарка, открытая сейчас. */
    public static function current() {
        if (is_admin()) {
            return null;
        }
        foreach (self::all() as $id => $page) {
            $page_id = (int) get_option(self::option_key($id));
            if ($page_id > 0 && is_page($page_id)) {
                $page['id'] = $id;
                return $page;
            }
        }
        return null;
    }

    public static function is_page() {
        return self::current() !== null;
    }

    public static function body_class($classes) {
        if (self::current()) {
            $classes[] = 'gs-gift-page';
            $classes[] = 'gs-chrome';
        }
        return $classes;
    }

    public static function title_parts($parts) {
        $page = self::current();
        if ($page) {
            $parts['title'] = $page['seo_title'];
            unset($parts['tagline']);
        }
        return $parts;
    }

    /**
     * Описание и адрес страницы.
     *
     * Тема и SEO-плагины на этих страницах видят только шорткод, поэтому
     * описание и canonical ставим здесь же, рядом с текстами.
     */
    public static function head() {
        $page = self::current();
        if (!$page) {
            return;
        }
        echo '<meta name="description" content="' . esc_attr($page['seo_desc']) . '">' . "\n";
        echo '<link rel="canonical" href="' . esc_url(self::get_url($page['id'])) . '">' . "\n";

        $faq = array();
        foreach ((array) $page['faq'] as $pair) {
            $faq[] = array(
                '@type'          => 'Question',
                'name'           => $pair[0],
                'acceptedAnswer' => array('@type' => 'Answer', 'text' => wp_strip_all_tags($pair[1])),
            );
        }
        if ($faq) {
            echo '<script type="application/ld+json">'
                . wp_json_encode(array(
                    '@context'   => 'https://schema.org',
                    '@type'      => 'FAQPage',
                    'mainEntity' => $faq,
                ), JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES)
                . '</script>' . "\n";
        }
    }

