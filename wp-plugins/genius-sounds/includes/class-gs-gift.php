    /**
     * Перелинковка внутри блока.
     *
     * Страницы под хвосты держатся вместе: человек, пришедший на «песню
     * маме», часто уходит выбирать подарок папе или на юбилей. Заодно это
     * то, что поиск читает как связный раздел, а не как набор одиночек.
     */
    private static function render_cross($page) {
        $others = array();
        foreach (self::all() as $id => $item) {
            if ($id === $page['id']) {
                continue;
            }
            $others[] = array('url' => self::get_url($id), 'menu' => $item['menu'], 'h1' => $item['h1']);
        }
        ?>
        <section class="gs-gift-sec gs-gift-cross">
            <h2 class="gs-gift-h2">Другие поводы и адресаты</h2>
            <ul>
                <?php foreach ($others as $other): ?>
                    <li><a href="<?php echo esc_url($other['url']); ?>"><?php echo esc_html($other['menu']); ?></a>
                        <span><?php echo esc_html($other['h1']); ?></span></li>
                <?php endforeach; ?>
            </ul>
            <p class="gs-gift-note">Хотите сделать сами и дешевле — инструменты открыты:
                <a href="/tekst-pesni/">текст песни</a>,
                <a href="/sozdat-muzyku/">создать музыку</a>,
                <a href="/pesnya-svoim-golosom/">песня своим голосом</a>,
                <a href="/oblozhka-dlya-treka/">обложка для трека</a>.</p>
        </section>
        <?php
    }
