        }

        $contact = trim((string) ($fields['contact'] ?? ''));
        if ($contact === '') {
            return array('ok' => false, 'message' => 'Оставьте контакт: телефон, почту или ник в Telegram');
        }

        $story = trim((string) ($fields['story'] ?? ''));
        if (mb_strlen($story) > 4000) {
            $story = mb_substr($story, 0, 4000);
        }

        $whom     = trim((string) ($fields['whom'] ?? ''));
        $name     = trim((string) ($fields['name'] ?? ''));
        $occasion = trim((string) ($fields['occasion'] ?? ''));
        $style    = trim((string) ($fields['style'] ?? ''));
        $pack     = trim((string) ($fields['pack'] ?? ''));
        $urgent   = !empty($fields['urgent']);
        $page     = sanitize_title((string) ($fields['page'] ?? self::root()));

        $lines = array();
        $lines[] = 'Кому: ' . ($whom !== '' ? $whom : 'не указано')
            . ($name !== '' ? ' (имя: ' . $name . ')' : '');
        $lines[] = 'Повод: ' . ($occasion !== '' ? $occasion : 'не указан');
        $lines[] = 'Звучание: ' . ($style !== '' ? $style : 'подобрать');
        $lines[] = 'Пакет: ' . ($pack !== '' ? $pack : 'не выбран');
        if ($urgent) {
            $lines[] = 'СРОЧНО — нужно сегодня';
        }
        $lines[] = 'Страница: ' . $page;
        if ($story !== '') {
            $lines[] = 'История: ' . $story;
        }

        $res = GS_Leads::accept(array(
            'name'    => $name !== '' ? $name : $whom,
            'contact' => $contact,
            'comment' => implode("\n", $lines),
            'source'  => 'песня в подарок: ' . $page,
        ));

        if (!empty($res['ok'])) {
            self::note($page);
        }
        return $res;
    }

