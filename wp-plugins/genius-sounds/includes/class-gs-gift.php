    const LABEL_PREFIX = 'gift_';

    /** Сколько текстов в сутки с одного адреса — модель стоит денег. */
    const FREE_PER_DAY = 5;

    /**
     * Шаг первый: собрать текст по анкете.
     *
     * Текст отдаём бесплатно и сразу. Это и примерка («видно, что песня
     * будет про моего человека»), и защита от пустых оплат: тот, кому текст
     * не понравился, просто не платит.
     *
     * @return array{ok:bool,order:string,lyrics:string,message:string}
     */
    public static function start($fields) {
        $out = array('ok' => false, 'order' => '', 'lyrics' => '', 'message' => '');

        $story = trim((string) ($fields['story'] ?? ''));
        $whom  = trim((string) ($fields['whom'] ?? ''));
        $name  = trim((string) ($fields['name'] ?? ''));
        if ($name === '' && $story === '') {
            $out['message'] = 'Напишите хотя бы имя и пару деталей про человека';
            return $out;
        }

        if (!self::allow_free()) {
            $out['message'] = 'Сегодня уже собрано пять текстов с этого адреса. '
                . 'Попробуйте завтра или напишите нам в поддержку.';
            return $out;
        }

        $res = GS_Provider::chat(self::writer_system(), self::writer_task($fields), array(
            'temperature' => 0.9,
            'max_tokens'  => 1200,
            'timeout'     => 120,
        ));
        if (empty($res['ok'])) {
            $out['message'] = 'Не получилось собрать текст: ' . (string) $res['message'];
            return $out;
        }

        $lyrics = self::clean_lyrics((string) $res['content']);
        if (mb_strlen($lyrics) < 200) {
            $out['message'] = 'Текст получился слишком коротким — добавьте деталей в анкету';
            return $out;
        }

        $order = wp_generate_password(16, false, false);
        update_option(self::ORDER_PREFIX . $order, array(
            'created'  => time(),
            'status'   => 'lyrics',
            'whom'     => $whom,
            'name'     => $name,
            'occasion' => trim((string) ($fields['occasion'] ?? '')),
            'style'    => trim((string) ($fields['style'] ?? '')),
            'pack'     => trim((string) ($fields['pack'] ?? '')),
            'contact'  => trim((string) ($fields['contact'] ?? '')),
            'page'     => sanitize_title((string) ($fields['page'] ?? self::root())),
            'story'    => mb_substr($story, 0, 4000),
            'lyrics'   => $lyrics,
            'task'     => '',
            'files'    => array(),
        ), false);

        self::note_free();
        $out['ok'] = true;
        $out['order'] = $order;
        $out['lyrics'] = $lyrics;
        return $out;
    }

    /**
     * Пометить заказ оплаченным вручную.
     *
     * Нужно, когда деньги пришли, а уведомление потерялось: без этой
     * возможности единственным выходом было бы лезть в базу руками.
     * Доступно только администратору.
     */
    public static function force($id) {
        $row = self::order($id);
        if (!$row) {
            return array('ok' => false, 'message' => 'заказ не найден');
        }
        $row['status'] = 'paid';
        $row['forced'] = time();
        self::save($id, $row);
        return self::sing($id);
    }

    /** Заказ по коду. */
    public static function order($id) {
        $id = preg_replace('~[^A-Za-z0-9]~', '', (string) $id);
        if ($id === '') {
            return null;
        }
        $row = get_option(self::ORDER_PREFIX . $id, null);
        return is_array($row) ? $row : null;
    }

    private static function save($id, $row) {
        update_option(self::ORDER_PREFIX . preg_replace('~[^A-Za-z0-9]~', '', (string) $id), $row, false);
    }

    /** Ссылка на оплату выбранного пакета. */
    public static function pay_link($id, $pack_key) {
        $row = self::order($id);
        if (!$row) {
            return '';
        }
        $packs = self::packs();
        $pack = isset($packs[$pack_key]) ? $packs[$pack_key] : $packs['song'];
        $row['pack'] = $pack['title'];
        $row['price'] = (int) $pack['price'];
        self::save($id, $row);

        if (!class_exists('KIE_TTS_Payment')) {
            return '';
        }
        return KIE_TTS_Payment::build_yoomoney_link(self::LABEL_PREFIX . $id, (float) $pack['price']);
    }

    /**
     * Деньги пришли — можно петь.
     *
     * Вызывается из приёмника уведомлений ЮMoney по метке заказа.
     */
    public static function paid($label) {
        $id = substr((string) $label, strlen(self::LABEL_PREFIX));
        $row = self::order($id);
        if (!$row) {
            return array('ok' => false, 'message' => 'заказ не найден');
        }
        if (($row['status'] ?? '') === 'singing' || ($row['status'] ?? '') === 'done') {
            return array('ok' => true, 'message' => 'уже в работе');
        }
        $row['status'] = 'paid';
        $row['paid_at'] = time();
        self::save($id, $row);

        $started = self::sing($id);
        return array('ok' => !empty($started['ok']), 'message' => (string) ($started['message'] ?? ''));
    }

    /**
     * Запустить запись песни по сохранённому тексту.
     *
     * Отдельным методом, потому что запуск нужен и сразу после оплаты, и
     * при опросе состояния: если поставщик в момент оплаты молчал, заказ не
     * должен зависнуть навсегда — следующий же опрос повторит попытку.
     */
    public static function sing($id) {
        $row = self::order($id);
        if (!$row || !in_array((string) ($row['status'] ?? ''), array('paid', 'singing'), true)) {
            return array('ok' => false, 'message' => 'заказ не оплачен');
        }
        if (!empty($row['task'])) {
            return array('ok' => true, 'message' => 'уже запущено');
        }

        $style = (string) ($row['style'] ?? '');
        if ($style === '' || strpos($style, 'не знаю') === 0) {
            $style = 'русская эстрада, тёплое звучание, средний темп';
        }
        $title = trim(((string) ($row['name'] ?? '')) . ' — песня в подарок');

        $res = GS_Lab::create_task('music', array(
            'prompt' => $style,
            'fields' => array(
                'instrumental' => false,
                'lyrics'       => (string) ($row['lyrics'] ?? ''),
                'style'        => $style,
                'title'        => mb_substr($title, 0, 80),
            ),
        ));
        if (empty($res['ok'])) {
            return array('ok' => false, 'message' => (string) $res['message']);
        }

        $row['status'] = 'singing';
        $row['task'] = (string) $res['task_id'];
        $row['sing_at'] = time();
        self::save($id, $row);
        return array('ok' => true, 'message' => '');
    }

    /**
     * Состояние заказа для страницы.
     *
     * @return array{status:string,lyrics:string,files:array,message:string,pack:string}
     */
    public static function state($id) {
        $row = self::order($id);
        if (!$row) {
            return array('status' => 'none', 'lyrics' => '', 'files' => array(),
                         'message' => 'Заказ не найден', 'pack' => '');
        }

        $status = (string) ($row['status'] ?? '');

        // Оплата прошла, а запуск не случился — повторяем здесь же.
        if ($status === 'paid' && empty($row['task'])) {
            self::sing($id);
            $row = self::order($id);
            $status = (string) ($row['status'] ?? '');
        }

        if ($status === 'singing' && !empty($row['task'])) {
            $task = GS_Lab::fetch_task('music', (string) $row['task']);
            $files = isset($task['files']) && is_array($task['files']) ? $task['files'] : array();
            if ((string) ($task['status'] ?? '') === 'completed' && $files) {
                $saved = array();
                foreach (array_slice($files, 0, 2) as $file) {
                    $url = (string) ($file['url'] ?? '');
                    if ($url === '') {
                        continue;
                    }
                    $copy = class_exists('GS_Songs') ? GS_Songs::store_copy($url) : '';
                    $saved[] = $copy !== '' ? $copy : $url;
                }
                if ($saved) {
                    $row['status'] = 'done';
                    $row['files'] = $saved;
                    $row['done_at'] = time();
                    self::save($id, $row);
                    $status = 'done';
                    self::tell($id, $row);
                }
            } elseif ((string) ($task['status'] ?? '') === 'failed') {
                $row['status'] = 'failed';
                $row['message'] = (string) ($task['message'] ?? '');
                self::save($id, $row);
                $status = 'failed';
                self::tell($id, $row);
            }
        }

        return array(
            'status'  => $status,
            'lyrics'  => (string) ($row['lyrics'] ?? ''),
            'files'   => (array) ($row['files'] ?? array()),
            'pack'    => (string) ($row['pack'] ?? ''),
            'message' => (string) ($row['message'] ?? ''),
        );
    }

