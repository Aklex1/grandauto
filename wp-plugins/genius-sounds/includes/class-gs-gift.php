    /** Убрать пояснения модели, оставить сам текст. */
    private static function clean_lyrics($raw) {
        $text = trim((string) $raw);
        $text = preg_replace('~^```[a-z]*\s*~i', '', $text);
        $text = preg_replace('~```$~', '', $text);
        $text = preg_replace('~^(вот|конечно|держите)[^\n]*\n~iu', '', $text);
        return trim($text);
    }

