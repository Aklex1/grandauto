    /** Страница «маме» должна открываться с уже выбранным «маме». */
    private static function preselect_whom($page, $value) {
        $map = array(
            'pesnya-v-podarok-mame'      => 'маме',
            'pesnya-v-podarok-pape'      => 'папе',
            'pesnya-v-podarok-synu'      => 'сыну',
            'pesnya-v-podarok-bratu'     => 'брату',
            'pesnya-v-podarok-uchitelyu' => 'учителю',
        );
        $want = $map[$page['id']] ?? '';
        return $want !== '' && $want === $value;
    }

