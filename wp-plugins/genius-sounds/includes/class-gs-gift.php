    /* ---------------------------------------------------------------------
     * Заказ: текст сразу, песня после оплаты
     *
     * Обещание «через десять минут» держится только на автоматике: анкета
     * уходит в модель, та собирает текст, человек его видит и решает, петь
     * ли. Оплата — обычной ссылкой ЮMoney с меткой заказа, и по уведомлению
     * о зачислении запускается запись. Регистрация не нужна нигде: барьер
     * входа на подарке стоит дороже, чем защита от случайных заказов.
     * ------------------------------------------------------------------ */

