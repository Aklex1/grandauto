    /** @return array<int,array{title:string,about:string,url:string,style:string}> */
    public static function samples() {
        $rows = get_option(self::OPT_SAMPLES, array());
        if (!is_array($rows)) {
            return array();
        }
        $out = array();
        foreach ($rows as $row) {
            if (is_array($row) && !empty($row['url'])) {
                $out[] = array(
                    'title' => (string) ($row['title'] ?? 'Пример'),
                    'about' => (string) ($row['about'] ?? ''),
                    'url'   => (string) $row['url'],
                    'style' => (string) ($row['style'] ?? ''),
                );
            }
        }
        return $out;
    }

