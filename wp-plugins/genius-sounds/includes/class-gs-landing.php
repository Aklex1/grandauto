    public static function get($id) {
        $all = self::all();
        return isset($all[$id]) ? $all[$id] : null;
    }

    public static function option_key($id) {
        return 'gs_landing_page_' . str_replace('-', '_', $id);
    }

    public static function get_url($id) {
        $landing = self::get($id);
        if (!$landing) {
            return '';
        }
        $page_id = (int) get_option(self::option_key($id));
        $url = $page_id > 0 ? get_permalink($page_id) : '';
        return $url ? $url : home_url('/' . $landing['slug'] . '/');
    }

    /* ---------------------------------------------------------------------
     * Страницы
     * ------------------------------------------------------------------ */

    public static function ensure_pages() {
        foreach (self::all() as $landing) {
            $option = self::option_key($landing['id']);
            $page_id = (int) get_option($option);
            if ($page_id > 0 && get_post($page_id)) {
                continue;
            }
            $shortcode = '[genius_landing id="' . $landing['id'] . '"]';
            $existing = get_page_by_path($landing['slug']);
            if ($existing) {
                $page_id = (int) $existing->ID;
                wp_update_post(array(
                    'ID'           => $page_id,
                    'post_title'   => $landing['seo_title'],
                    'post_content' => $shortcode,
                    'post_status'  => 'publish',
                ));
            } else {
                $page_id = (int) wp_insert_post(array(
                    'post_title'   => $landing['seo_title'],
                    'post_content' => $shortcode,
                    'post_status'  => 'publish',
                    'post_type'    => 'page',
                    'post_name'    => $landing['slug'],
                ));
            }
            if ($page_id > 0) {
                update_option($option, $page_id, false);
            }
        }
    }

    /**
     * Посадочная текущего запроса.
     *
     * @return array|null
     */
    public static function current() {
        if (is_admin()) {
            return null;
        }
        foreach (self::all() as $landing) {
            $page_id = (int) get_option(self::option_key($landing['id']));
            if ($page_id > 0 && is_page($page_id)) {
                return $landing;
            }
        }
        global $post;
        if ($post instanceof WP_Post && has_shortcode((string) $post->post_content, 'genius_landing')) {
            foreach (self::all() as $landing) {
                if (strpos((string) $post->post_content, 'id="' . $landing['id'] . '"') !== false) {
                    return $landing;
                }
            }
        }
        return null;
    }

    /** Инструмент, который показывает текущая посадочная. */
    public static function current_service() {
        $landing = self::current();
        return $landing ? GS_Lab::get_service($landing['service']) : null;
    }

    public static function body_class($classes) {
        if (self::current()) {
            $classes[] = 'gs-lab-page';
            $classes[] = 'gs-studio-page';
            $classes[] = 'gs-chrome';
        }
        return $classes;
    }

