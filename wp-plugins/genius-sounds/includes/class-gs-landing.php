    /**
     * Сервис с заголовками посадочной: та же машинка, другие тексты.
     *
     * @return array|null
     */
    public static function as_service($landing) {
        $service = GS_Lab::get_service($landing['service']);
        if (!$service) {
            return null;
        }
        $service['h1']        = $landing['h1'];
        $service['lead']      = $landing['lead'];
        $service['badge']     = $landing['badge'];
        $service['menu']      = $landing['menu'];
        $service['seo_title'] = $landing['seo_title'];
        $service['seo_desc']  = $landing['seo_desc'];
        $service['faq']       = $landing['faq'];
        return $service;
    }

    public static function render($atts = array()) {
        $atts = shortcode_atts(array('id' => ''), (array) $atts, 'genius_landing');
        $landing = self::get(sanitize_title($atts['id']));
        if (!$landing) {
            return '';
        }
        $service = self::as_service($landing);
        if (!$service) {
            return '';
        }

        $body = '';
        foreach ((array) $landing['body'] as $block) {
            $body .= '<h2 class="gs-section-title">' . esc_html($block[0]) . '</h2>'
                . '<div class="gs-prose">' . $block[1] . '</div>';
        }

        return GS_Lab_Page::compose($service, array(
            'crumb'       => $landing['crumb'],
            'body_html'   => $body,
            'cross_title' => 'Что ещё можно сделать со звуком и видео',
            'back_url'    => self::get_url($landing['id']),
            'landing_id'  => $landing['id'],
        ));
    }
