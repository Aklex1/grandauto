    public static function get_cost($id) {
        $service = self::get_service($id);
        if (!$service) {
            return 0.0;
        }
        // «Минимум» — настройка поминутной и посекундной оплаты. У сервиса с
        // фиксированной ценой её быть не должно: иначе случайно сохранённое
        // значение делает платной операцию, которая ничего не стоит.
        if ((string) self::pricing($id, 'unit') !== 'fixed') {
            $min = self::saved_number('gs_lab_min_' . $id, self::pricing($id, 'min'));
            if ($min > 0) {
                return round($min, 2);
            }
        }
        return round(self::saved_number($service['cost_option'], $service['cost']), 2);
    }

    /* ---------------------------------------------------------------------
     * Цена от длительности
     *
     * Поставщики берут деньги за секунды и минуты обработки, поэтому и здесь
     * цена считается от длины файла: короткий ролик стоит минимум, длинный
     * не уводит сервис в минус.
     * ------------------------------------------------------------------ */

    public static function pricing($id, $key) {
        $service = self::get_service($id);
        $pricing = ($service && !empty($service['pricing'])) ? $service['pricing'] : array();
        $defaults = array('unit' => 'fixed', 'rate' => 0, 'min' => 0, 'max_seconds' => 0);
        $pricing = array_merge($defaults, $pricing);
        return $pricing[$key];
    }

    public static function rate($id) {
        // У сервиса с фиксированной ценой ставки нет вовсе, и случайно
        // сохранённое значение не должно делать его платным.
        if ((string) self::pricing($id, 'unit') === 'fixed') {
            return 0.0;
        }
        return round(self::saved_number('gs_lab_rate_' . $id, self::pricing($id, 'rate')), 2);
    }

    public static function max_seconds($id) {
        return (int) self::saved_number('gs_lab_max_seconds_' . $id, self::pricing($id, 'max_seconds'));
    }

    /**
     * Итоговая цена обработки файла длительностью $seconds.
     */
    public static function price($id, $seconds, $fields = array()) {
        $min  = self::get_cost($id);
        $unit = (string) self::pricing($id, 'unit');
        $seconds = (float) $seconds;

        // Подборка стоит столько кадров, сколько в ней заказали: цена за
        // кадр одна, а длительности у картинки нет — считать не по чему.
        if ($id === 'photo') {
            return round($min * self::photo_count(is_array($fields) ? ($fields['count'] ?? 5) : 5), 2);
        }

        if ($unit === 'fixed' || $seconds <= 0) {
            return $min;
        }
        $units = $unit === 'second' ? ceil($seconds) : ceil($seconds / 60);
        $price = self::rate($id) * $units;
        return round(max($min, $price), 2);
    }

    /**
     * Понятная подпись цены для страницы сервиса.
     */
    public static function price_hint($id) {
        $unit = (string) self::pricing($id, 'unit');
        $cost = self::get_cost($id);
        $min  = number_format_i18n($cost, 0);
        if ($cost <= 0 && self::rate($id) <= 0) {
            return 'бесплатно';
        }
        if ($id === 'photo') {
            // Цена за обработку тут ничего не говорит: заказывают подборку,
            // и человеку нужно сразу видеть, во что обойдётся набор.
            return $min . ' ₽ за кадр — подборка от ' . number_format_i18n($cost * 3, 0) . ' ₽';
        }
        if ($unit === 'fixed') {
            return $min . ' ₽ за обработку';
        }
        $rate = number_format_i18n(self::rate($id), 0);
        $word = $unit === 'second' ? 'секунду видео' : 'минуту записи';
        return $rate . ' ₽ за ' . $word . ', минимум ' . $min . ' ₽';
    }

    /**
     * Длительность аудио или видео из нашей же папки загрузок.
     * Нужна и для цены, и для ограничения длины файла.
     */
    public static function media_duration($path) {
        if (!is_string($path) || $path === '' || !file_exists($path)) {
            return 0.0;
        }
        if (!function_exists('wp_read_audio_metadata')) {
            require_once ABSPATH . 'wp-admin/includes/media.php';
