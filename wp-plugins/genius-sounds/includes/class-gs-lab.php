    private static function post_json($url, $payload) {
        $key = self::api_key();
        if ($key === '') {
            return array('ok' => false, 'message' => 'Генерация временно недоступна: не настроен доступ к сервису', 'body' => array());
        }
        $response = wp_remote_post($url, array(
            'timeout' => 45,
            'headers' => array(
                'Authorization' => 'Bearer ' . $key,
                'Content-Type'  => 'application/json',
            ),
            'body'    => wp_json_encode($payload),
        ));
        if (is_wp_error($response)) {
            return array('ok' => false, 'message' => $response->get_error_message(), 'body' => array());
        }
        $body = json_decode((string) wp_remote_retrieve_body($response), true);
        if (!is_array($body)) {
            return array('ok' => false, 'message' => 'Некорректный ответ сервиса генерации', 'body' => array());
        }
        if ((int) ($body['code'] ?? 0) !== 200) {
            return array('ok' => false, 'message' => (string) ($body['msg'] ?? 'Сервис генерации вернул ошибку'), 'body' => $body);
        }
        return array('ok' => true, 'message' => '', 'body' => $body);
    }

    private static function get_json($url, $args) {
        $key = self::api_key();
        if ($key === '') {
            return array('ok' => false, 'message' => 'Генерация временно недоступна', 'body' => array());
        }
        $response = wp_remote_get(add_query_arg($args, $url), array(
            'timeout' => 45,
            'headers' => array('Authorization' => 'Bearer ' . $key),
        ));
        if (is_wp_error($response)) {
            return array('ok' => false, 'message' => $response->get_error_message(), 'body' => array());
        }
        $body = json_decode((string) wp_remote_retrieve_body($response), true);
        if (!is_array($body) || !isset($body['data'])) {
            return array('ok' => false, 'message' => 'Некорректный ответ сервиса генерации', 'body' => array());
        }
        return array('ok' => true, 'message' => '', 'body' => $body);
    }

    /**
     * Ставит задачу сервиса.
     *
     * @return array{ok:bool,task_id:string,message:string}
     */
    /**
     * Длительность записи по ссылке — нужна, чтобы посчитать цену до
     * запуска. Файл берём частями: полного скачивания для метаданных
     * не требуется.
     */
    public static function remote_duration($url) {
        $local = self::local_path($url);
        if ($local !== '') {
            return self::media_duration($local);
        }
        $response = wp_remote_get((string) $url, array('timeout' => 90, 'limit_response_size' => 26214400));
        if (is_wp_error($response) || (int) wp_remote_retrieve_response_code($response) !== 200) {
            return 0.0;
        }
        $body = (string) wp_remote_retrieve_body($response);
        if (strlen($body) < 1024) {
            return 0.0;
        }
        $tmp = wp_tempnam('gs-lab-audio');
        if (!$tmp) {
            return 0.0;
        }
        file_put_contents($tmp, $body);
        $seconds = self::media_duration($tmp);
        @unlink($tmp);
        return $seconds;
    }

    /**
     * Готовит задачу к оплате: приводит источник к ссылке на звук и
     * выясняет длительность. Без этого запись по ссылке считалась бы по
     * минимальной цене независимо от того, минута там или два часа.
     *
     * @return array{ok:bool,message:string,payload:array,seconds:float}
     */
    public static function prepare($id, $payload) {
        $out = array('ok' => true, 'message' => '', 'payload' => $payload, 'seconds' => 0.0);
        if ($id !== 'stt') {
            return $out;
        }

        $fields = isset($payload['fields']) && is_array($payload['fields']) ? $payload['fields'] : array();
        $link = trim((string) ($fields['source_url'] ?? ''));
        $audio = (string) ($payload['audio_url'] ?? '');

        if ($audio === '' && $link === '') {
            return array('ok' => false, 'message' => 'Загрузите запись или вставьте ссылку', 'payload' => $payload, 'seconds' => 0.0);
        }

        // Ссылка на ролик: дорожку достаём сразу — она нужна и для цены,
        // и для самой расшифровки, а извлечение идёт на нашей стороне.
        if ($audio === '' && !preg_match('~\.(mp3|wav|m4a|ogg|opus|aac|mp4|webm)(\?|$)~i', $link)) {
            if (!class_exists('KIE_TTS_API')) {
                return array('ok' => false, 'message' => 'Извлечение звука сейчас недоступно', 'payload' => $payload, 'seconds' => 0.0);
            }
            $data = KIE_TTS_API::create_youtube_audio_task($link, 'mp3');
            $extracted = is_array($data) && !empty($data['audio_url']) ? esc_url_raw((string) $data['audio_url']) : '';
            if ($extracted === '') {
                $message = is_array($data) && !empty($data['message']) ? (string) $data['message'] : 'Не удалось получить дорожку по этой ссылке';
                return array('ok' => false, 'message' => self::ytaudio_error($message), 'payload' => $payload, 'seconds' => 0.0);
            }
            $payload['audio_url'] = $extracted;
            $out['seconds'] = is_array($data) && !empty($data['duration']) ? (float) $data['duration'] : self::remote_duration($extracted);
            $out['payload'] = $payload;
            return $out;
        }

        if ($audio === '') {
            $payload['audio_url'] = esc_url_raw($link);
            $out['payload'] = $payload;
        }
        $source = (string) $payload['audio_url'];
        $local = self::local_path($source);
        $out['seconds'] = $local !== '' ? self::media_duration($local) : self::remote_duration($source);
        return $out;
    }

    /** Сколько помним о том, что служба извлечения лежит. */
    const YTA_DOWN_KEY = 'gs_yta_down';
    const YTA_DOWN_TTL = 900;

    /** Лежит ли служба извлечения прямо сейчас. */
    public static function ytaudio_down() {
        return (bool) get_transient(self::YTA_DOWN_KEY);
    }

    /** Отказ службы извлечения — на языке пользователя. */
    private static function ytaudio_error($message) {
        $low = mb_strtolower((string) $message);
        if (strpos($low, 'ключ') !== false || strpos($low, 'key') !== false) {
            return 'Служба извлечения звука не приняла ключ доступа — её нужно обновить на сервере.';
        }
        // «Не удалось соединиться» и «не ответила вовремя» — разные беды.
        // Первое значит, что машины со службой просто нет на связи, и совет
        // «попробуйте через минуту» тут превращается в обман: человек будет
        // пробовать весь день. Такое состояние запоминаем и честно говорим
        // о нём на странице сервиса.
        if (strpos($low, 'failed to connect') !== false || strpos($low, 'connection refused') !== false
            || strpos($low, 'could not connect') !== false || strpos($low, 'couldn\'t connect') !== false) {
            set_transient(self::YTA_DOWN_KEY, 1, self::YTA_DOWN_TTL);
            return 'Служба извлечения звука сейчас не на связи. Это наша поломка, не ваша — '
                 . 'мы уже знаем о ней. Пока можно загрузить файл с устройства.';
        }
        if (strpos($low, 'timeout') !== false || strpos($low, 'таймаут') !== false || strpos($low, 'timed out') !== false) {
            return 'Служба извлечения звука не ответила вовремя. Попробуйте ещё раз через минуту.';
        }
        if (strpos($low, 'sign in') !== false || strpos($low, 'age-restricted') !== false
            || strpos($low, 'private') !== false || strpos($low, 'members-only') !== false) {
            return 'Ролик требует входа в аккаунт или закрыт — дорожку снять нельзя.';
        }
        if (strpos($low, 'reload') !== false || strpos($low, 'unable to extract') !== false
            || strpos($low, 'player response') !== false) {
            return 'Площадка сменила выдачу, и служба её пока не понимает. Мы уже знаем, скоро поправим.';
        }
        if (strpos($low, 'unavailable') !== false || strpos($low, 'removed') !== false) {
            return 'Ролик недоступен: удалён или скрыт автором.';
        }
        if (strpos($low, 'duration') !== false) {
            return 'Ролик слишком длинный. Разрежьте запись или возьмите фрагмент покороче.';
        }
        return (string) $message;
    }

    /**
     * Короткое название трека из описания — когда пользователь его не задал.
     * Им пользуется и песня своим голосом, поэтому метод открытый.
     */
    public static function music_title($prompt) {
        $prompt = trim(preg_replace('~\s+~u', ' ', (string) $prompt));
        if ($prompt === '') {
            return 'Трек';
        }
        $words = preg_split('~\s+~u', $prompt);
        $words = array_slice($words, 0, 5);
        // Обрывок вида «бит для» выглядит небрежно: отбрасываем хвостовые
        // предлоги и союзы, на которых название повисает.
        $tail = array('для', 'под', 'из', 'в', 'на', 'с', 'и', 'о', 'по', 'к', 'от', 'до', 'при', 'без');
        while ($words && in_array(mb_strtolower(rtrim(end($words), ',.')), $tail, true)) {
            array_pop($words);
        }
        $title = trim(implode(' ', $words), " ,.;:-");
        if ($title === '') {
            return 'Трек';
        }
        return function_exists('mb_convert_case')
            ? mb_convert_case(mb_substr($title, 0, 1), MB_CASE_UPPER) . mb_substr($title, 1)
            : $title;
    }

    /** «3 мин 24 с» — подпись длительности трека. */
    private static function human_length($seconds) {
        $seconds = max(0, (int) $seconds);
        $m = intdiv($seconds, 60);
        $s = $seconds % 60;
        return $m > 0 ? $m . ' мин ' . $s . ' с' : $s . ' с';
    }

