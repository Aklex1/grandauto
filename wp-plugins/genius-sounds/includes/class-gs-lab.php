        if (!function_exists('wp_read_audio_metadata')) {
            return 0.0;
        }
        $meta = wp_read_audio_metadata($path);
        if (is_array($meta) && !empty($meta['length'])) {
            return (float) $meta['length'];
        }
        return 0.0;
    }

