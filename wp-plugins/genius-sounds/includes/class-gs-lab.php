    /** Кадрирование под выбранный формат. */
    private static function photo_frame_prompt($ratio) {
        $map = array(
            '3:4'  => 'Vertical portrait framing, aspect ratio 3:4.',
            '1:1'  => 'Square framing, subject centred, aspect ratio 1:1.',
            '9:16' => 'Tall vertical framing, waist-up composition, aspect ratio 9:16.',
            '16:9' => 'Wide horizontal framing, room on one side, aspect ratio 16:9.',
        );
        return isset($map[$ratio]) ? $map[$ratio] : $map['3:4'];
    }

    /**
     * Описание одного кадра подборки.
     *
     * Условие про лица повторяем в конце: модели сильнее слушают последние
     * предложения, а подменённое лицо обесценивает весь заказ.
     */
    public static function photo_prompt($place, $shot, $ratio, $extra, $sources = 1) {
        $prompt = $sources > 1
            ? 'Use the people from all the provided photos as the same people in one new photograph. '
            : 'Keep the people from the provided photo. ';
        $prompt .= 'Shot: ' . $shot . '. Location and styling: ' . $place . '. '
            . self::photo_frame_prompt($ratio);
        $extra = trim((string) $extra);
        if ($extra !== '') {
            $prompt .= ' Additional request: ' . $extra . '.';
        }
        $prompt .= ' Keep their exact faces, facial features, skin tone, hair colour and age unchanged.'
            . ' Do not invent new people and do not merge faces.'
            . ' Do not beautify or reshape the faces.'
            . ' Photorealistic photograph, natural skin texture, sharp focus on the eyes,'
            . ' no text, no watermark, no logos.';
        return mb_substr($prompt, 0, 1500);
    }

    public static function create_task($id, $params) {
        $callback = add_query_arg('token', GS_SFX::callback_token(), rest_url(GS_Rest::NS . '/lab/callback'));

        // Разделение дорожек и шумоподавление писались под отдельного
        // поставщика, которого так и не подключили, и держались на ручной
        // очереди. Теперь обе задачи умеет основной поставщик — он и стоит
        // по умолчанию, а music.ai и ручная обработка остались запасными
        // путями на случай, если один заказ придётся сделать вручную.
        //
        // Раньше здесь был тупик: без ключа music.ai и без ручного режима
        // запрос возвращал «Инструмент сейчас недоступен», а рабочая ветка
        // ниже не получала управление вовсе.
        if (class_exists('GS_MusicAI') && GS_MusicAI::handles($id)) {
            if (GS_MusicAI::ready($id)) {
                return GS_MusicAI::create_job($id, (string) $params['audio_url']);
            }
            if (GS_Manual::enabled($id)) {
                return GS_Manual::create_order($id, $params);
            }
        }

        // Модель и её параметры знает адаптер: если она ляжет, он сам
        // уведёт запрос на запасную, не трогая этот код.
        if ($id === 'cover') {
            $fields = isset($params['fields']) && is_array($params['fields']) ? $params['fields'] : array();
            $style  = trim((string) ($fields['style'] ?? ''));
            $ratio  = (string) ($fields['ratio'] ?? '1:1');
            if (!in_array($ratio, array('1:1', '16:9', '9:16'), true)) {
                $ratio = '1:1';
            }
            $prompt = trim((string) ($params['prompt'] ?? ''));
            if ($style !== '') {
                $prompt .= '. Оформление: ' . $style;
            }
            // Буквы просим не рисовать. Модели выводят текст неразборчиво —
            // вместо названия выходят закорючки, и обложку с ними площадки
            // отклоняют. Чистая картинка плюс подпись в редакторе честнее.
            $prompt .= '. Album cover artwork, striking composition, no text, no letters, '
                . 'no typography, no watermark, no logos';
            $res = GS_Provider::job('image', array(
                'prompt' => mb_substr($prompt, 0, 1200),
                'ratio'  => $ratio,
            ), array('callback' => $callback));
            return array('ok' => !empty($res['ok']), 'task_id' => (string) $res['task'], 'message' => (string) $res['message']);
        }

        // Нейрофотосессия: это правка кадра, а не рисование с нуля.
        // Модели генерации по описанию человека со снимка не знают — лица
        // вышли бы чужими, и весь смысл сервиса пропал бы.
        //
        // Подборка — несколько кадров сразу, поэтому у неё свой номер
        // задачи: страница опрашивает один адрес, а под ним лежит список
        // задач поставщика, по одной на локацию.
        if ($id === 'photo') {
            $fields = isset($params['fields']) && is_array($params['fields']) ? $params['fields'] : array();
            $sets   = self::photo_sets();
            $set    = (string) ($fields['set'] ?? 'family-home');
            if (!isset($sets[$set])) {
                $set = 'family-home';
            }
            $count  = self::photo_count($fields['count'] ?? 5);
            $extra  = trim((string) ($fields['extra'] ?? ''));
            $ratio  = (string) ($fields['ratio'] ?? '3:4');
            if (!in_array($ratio, array('3:4', '1:1', '9:16', '16:9'), true)) {
                $ratio = '3:4';
            }

            // Снимков может быть несколько — по человеку. Модель правки
            // принимает их списком и собирает кадр из всех разом.
            $images = array();
            foreach (array('image_url', 'image2_url', 'image3_url', 'image4_url') as $key) {
                $url = trim((string) ($params[$key] ?? ''));
                if ($url !== '') {
                    $images[] = $url;
                }
            }
            if (empty($images)) {
                return array('ok' => false, 'task_id' => '', 'message' => 'Нужен хотя бы один снимок');
            }

            $scenes = array_slice($sets[$set]['shots'], 0, $count);
            $jobs = array();
            foreach ($scenes as $shot) {
                $res = GS_Provider::job('image_edit', array(
                    'prompt'     => self::photo_prompt($sets[$set]['place'], $shot[1], $ratio, $extra, count($images)),
                    'image_urls' => $images,
                    'image_url'  => $images[0],
                    'ratio'      => $ratio,
                ), array('callback' => $callback));
                $jobs[] = array(
                    'label' => (string) $shot[0],
                    'task'  => !empty($res['ok']) ? (string) $res['task'] : '',
                    'error' => !empty($res['ok']) ? '' : (string) $res['message'],
                );
                usleep(300000); // не ставим семь задач в одну секунду
            }

            $started = array_filter($jobs, function ($j) { return $j['task'] !== ''; });
            if (empty($started)) {
                $first = reset($jobs);
                return array('ok' => false, 'task_id' => '',
                             'message' => $first && $first['error'] !== '' ? $first['error'] : 'Поставщик не принял задачу');
            }

            $task_id = 'photoset-' . wp_generate_password(20, false, false);
            set_transient('gs_lab_photoset_' . $task_id, array(
                'set'   => $set,
                'ratio' => $ratio,
                'jobs'  => $jobs,
            ), DAY_IN_SECONDS);
            return array('ok' => true, 'task_id' => $task_id, 'message' => '');
        }

        if ($id === 'dub') {
            $fields = isset($params['fields']) && is_array($params['fields']) ? $params['fields'] : array();
            $speech = trim((string) ($fields['speech'] ?? ''));
            if (mb_strlen($speech) > 5000) {
                $speech = mb_substr($speech, 0, 5000);
            }
            $lang = (string) ($fields['lang'] ?? '');
            $video = (string) $params['video_url'];

            // Свой номер задачи: у дубляжа до трёх заходов к поставщику
            // подряд, а страница должна опрашивать один адрес от начала до
            // конца.
            $task_id = 'dub-' . wp_generate_password(20, false, false);
            $row = array(
                'stage'     => '',
                'stt_task'  => '',
                'tts_task'  => '',
                'lip_task'  => '',
                'video_url' => $video,
                'lang'      => $lang,
                'text'      => $speech,
            );

            if ($speech === '') {
                // Текста нет — значит озвучиваем то, что сказано в ролике.
                $created = GS_Transcribe::create(
                    array('audio_url' => $video),
                    (int) ($params['user_id'] ?? 0)
                );
                if (is_wp_error($created)) {
                    return array('ok' => false, 'task_id' => '', 'message' => $created->get_error_message());
                }
                $row['stage'] = 'stt';
                $row['stt_task'] = (string) $created['id'];
                set_transient('gs_lab_dub_' . $task_id, $row, DAY_IN_SECONDS);
                return array('ok' => true, 'task_id' => $task_id, 'message' => '');
            }

            $speech = self::dub_translate($speech, $lang);
            if ($speech === '') {
                return array('ok' => false, 'task_id' => '',
                             'message' => 'Не удалось перевести текст — попробуйте ещё раз');
            }

            $voiced = GS_Tts_Fallback::create_task($speech, '');
            if (empty($voiced['ok'])) {
                return array('ok' => false, 'task_id' => '',
                             'message' => (string) ($voiced['message'] ?: 'Озвучка сейчас недоступна'));
            }
            $row['stage'] = 'tts';
            $row['tts_task'] = (string) $voiced['task_id'];
            $row['text'] = $speech;
            set_transient('gs_lab_dub_' . $task_id, $row, DAY_IN_SECONDS);
            return array('ok' => true, 'task_id' => $task_id, 'message' => '');
        }

        if ($id === 'vupscale') {
            // Множитель кадра не передаём. Поставщик его принимает — и «2»,
            // и «4» проходят проверку, — но размер кадра от этого не
            // меняется: проверено на своём файле, 464x640 на входе и
            // 464x640 на выходе. Обещать увеличение, которого нет, нельзя,
            // поэтому сервис делает то, что делает на самом деле: чистит
            // запись и возвращает резкость.
            $res = self::post_json(self::API_JOBS, array(
                'model' => 'topaz/video-upscale',
                'input' => array('video_url' => (string) $params['video_url']),
                'callBackUrl' => $callback,
            ));
            $task = $res['ok'] ? (string) ($res['body']['data']['taskId'] ?? '') : '';
            return array('ok' => $res['ok'] && $task !== '', 'task_id' => $task, 'message' => $res['message']);
        }

        if ($id === 'avatar') {
            $res = GS_Provider::job('avatar', array(
                'image_url' => (string) $params['image_url'],
                'audio_url' => (string) $params['audio_url'],
                'prompt'    => (string) ($params['prompt'] ?? ''),
            ), array('callback' => $callback));
            return array('ok' => !empty($res['ok']), 'task_id' => (string) $res['task'], 'message' => (string) $res['message']);
        }

        if ($id === 'stt') {
            $fields = isset($params['fields']) && is_array($params['fields']) ? $params['fields'] : array();
            $link = trim((string) ($fields['source_url'] ?? ''));
            $audio = (string) ($params['audio_url'] ?? '');
            if ($audio === '' && $link === '') {
                return array('ok' => false, 'task_id' => '', 'message' => 'Загрузите запись или вставьте ссылку');
            }

            // Источник уже разобран при расчёте цены: сюда приходит ссылка
            // на звук, даже если пользователь дал ссылку на ролик.
            $source = array(
                'audio_url'        => $audio !== '' ? $audio : $link,
                'language_code'    => trim((string) ($fields['language'] ?? '')),
                'tag_audio_events' => !empty($fields['events']),
                'diarize'          => !empty($fields['diarize']),
            );

            $created = GS_Transcribe::create($source, (int) ($params['user_id'] ?? 0));
            if (is_wp_error($created)) {
                return array('ok' => false, 'task_id' => '', 'message' => $created->get_error_message());
            }
            return array('ok' => true, 'task_id' => (string) $created['id'], 'message' => '');
        }

        if ($id === 'ytaudio') {
            $fields = isset($params['fields']) && is_array($params['fields']) ? $params['fields'] : array();
            $url = esc_url_raw(trim((string) ($fields['url'] ?? '')));
            if ($url === '') {
                return array('ok' => false, 'task_id' => '', 'message' => 'Вставьте ссылку на ролик');
            }
            $format = strtolower(trim((string) ($fields['format'] ?? 'mp3')));
            if (!in_array($format, array('mp3', 'wav', 'm4a'), true)) {
                $format = 'mp3';
            }
            if (!class_exists('KIE_TTS_API')) {
                return array('ok' => false, 'task_id' => '', 'message' => 'Извлечение звука сейчас недоступно');
            }

            // Служба отвечает сразу, очереди у неё нет: складываем готовый
            // ответ под своим номером, чтобы страница работала как обычно.
            $data = KIE_TTS_API::create_youtube_audio_task($url, $format);
            $audio = is_array($data) && !empty($data['audio_url']) ? esc_url_raw((string) $data['audio_url']) : '';
            if ($audio === '') {
                $message = is_array($data) && !empty($data['message'])
                    ? (string) $data['message']
                    : 'Не удалось получить дорожку по этой ссылке';
                return array('ok' => false, 'task_id' => '', 'message' => self::ytaudio_error($message));
            }

            $task_id = 'yta-' . wp_generate_password(20, false, false);
            $title = is_array($data) && !empty($data['title']) ? (string) $data['title'] : 'Звуковая дорожка';
            set_transient('gs_lab_yta_' . $task_id, array(
                'url'   => $audio,
                'title' => $title,
            ), DAY_IN_SECONDS);
            return array('ok' => true, 'task_id' => $task_id, 'message' => '');
        }

        if ($id === 'music') {
            $fields = isset($params['fields']) && is_array($params['fields']) ? $params['fields'] : array();
            $instrumental = !isset($fields['instrumental']) || !empty($fields['instrumental']);
            $lyrics = trim((string) ($fields['lyrics'] ?? ''));
            $style  = trim((string) ($fields['style'] ?? ''));
            $title  = trim((string) ($fields['title'] ?? ''));
            $prompt = trim((string) ($params['prompt'] ?? ''));

            // Свой текст песни поставщик принимает только в «своём» режиме,
            // где описание и стиль задаются отдельными полями.
            $custom = (!$instrumental && $lyrics !== '') || $style !== '' || $title !== '';

            $payload = array(
                'model'        => 'V5',
                'customMode'   => $custom,
                'instrumental' => $instrumental,
                'callBackUrl'  => $callback,
            );
            if ($custom) {
                // В своём режиме prompt — это текст песни, а описание уходит в стиль.
                $payload['style'] = mb_substr($style !== '' ? $style : $prompt, 0, 200);
                $payload['title'] = mb_substr($title !== '' ? $title : self::music_title($prompt), 0, 80);
                $payload['prompt'] = $instrumental ? '' : mb_substr($lyrics !== '' ? $lyrics : $prompt, 0, 2500);
                if ($instrumental) {
                    unset($payload['prompt']);
                }
            } else {
                $payload['prompt'] = mb_substr($prompt, 0, 1000);
            }

            $res = self::post_json(self::API_MUSIC, $payload);
            $task = $res['ok'] ? (string) ($res['body']['data']['taskId'] ?? '') : '';
            return array('ok' => $res['ok'] && $task !== '', 'task_id' => $task, 'message' => $res['message']);
        }

        if ($id === 'lyrics') {
            $fields = isset($params['fields']) && is_array($params['fields']) ? $params['fields'] : array();
            $style  = trim((string) ($fields['style'] ?? ''));
            $prompt = trim((string) ($params['prompt'] ?? ''));
            // Жанр поставщик отдельным полем не принимает — дописываем в
            // описание, иначе он просто потеряется по дороге.
            if ($style !== '') {
                $prompt .= '. Жанр и настроение: ' . $style;
            }
            $res = self::post_json(self::API_LYRICS, array(
                'prompt'      => mb_substr($prompt, 0, 1000),
                'callBackUrl' => $callback,
            ));
            $task = $res['ok'] ? (string) ($res['body']['data']['taskId'] ?? '') : '';
            return array('ok' => $res['ok'] && $task !== '', 'task_id' => $task, 'message' => $res['message']);
        }

        // Разделение дорожек обслуживает две разные задачи: «убрать вокал»
        // отдаёт минусовку, «убрать шум» — ту же дорожку с голосом, только
        // без всего остального. Модель одна, отличаются лишь тем, какой стем
        // показываем человеку.
        if ($id === 'vocal' || $id === 'denoise') {
            // audioId сюда слать нельзя: поставщик считает его ссылкой на
            // свою прежнюю задачу и отвечает «retry with taskId and audioId».
            // Со своей строкой запрос падал всегда — сервис не работал.
            $res = self::post_json(self::API_VOCAL, array(
                'audioUrl'    => (string) $params['audio_url'],
                'type'        => 'separate_vocal',
                'stemName'    => 'Vocals',
                'callBackUrl' => $callback,
            ));
            $task = $res['ok'] ? (string) ($res['body']['data']['taskId'] ?? '') : '';
            return array('ok' => $res['ok'] && $task !== '', 'task_id' => $task, 'message' => $res['message']);
        }

        return array('ok' => false, 'task_id' => '', 'message' => 'Неизвестный сервис');
    }

    /**
     * Статус задачи.
     *
     * @return array{ok:bool,status:string,files:array,message:string}
     */
    /**
     * Состояние подборки.
     *
     * Каждый кадр — своя задача у поставщика. Один неудавшийся кадр не
     * должен хоронить всю подборку: собираем то, что получилось, и
     * сообщаем, сколько кадров не вышло — деньги за них вернёт вызывающий.
     */
    private static function photoset_state($task_id) {
        $out = array('ok' => true, 'status' => 'pending', 'files' => array(), 'text' => '', 'message' => '');
        $row = get_transient('gs_lab_photoset_' . $task_id);
        if (!is_array($row) || empty($row['jobs'])) {
            $out['status'] = 'failed';
            $out['message'] = 'Задача не найдена — попробуйте запустить подборку заново';
            return $out;
        }

        $jobs = $row['jobs'];
        $ready = 0;
        $failed = 0;
        $changed = false;

        foreach ($jobs as $i => $job) {
            if (!empty($job['url']) || !empty($job['done'])) {
                $ready += empty($job['url']) ? 0 : 1;
                $failed += empty($job['url']) ? 1 : 0;
                continue;
            }
            if ($job['task'] === '') {
                $jobs[$i]['done'] = 1;
                $failed++;
                $changed = true;
                continue;
            }
            $state = GS_Provider::job_state($job['task']);
            if (!empty($state['urls'])) {
                $jobs[$i]['url'] = (string) $state['urls'][0];
                $jobs[$i]['done'] = 1;
                $ready++;
                $changed = true;
            } elseif (stripos((string) ($state['state'] ?? ''), 'fail') !== false) {
                $jobs[$i]['done'] = 1;
                $failed++;
                $changed = true;
            }
        }

        if ($changed) {
            $row['jobs'] = $jobs;
            set_transient('gs_lab_photoset_' . $task_id, $row, DAY_IN_SECONDS);
        }

        $total = count($jobs);
        if ($ready + $failed < $total) {
            $out['message'] = sprintf('Готово %d из %d', $ready, $total);
            return $out;
        }

        if ($ready === 0) {
            $out['status'] = 'failed';
            $out['message'] = 'Ни один кадр не удался, деньги возвращены';
            return $out;
        }

        foreach ($jobs as $job) {
            if (empty($job['url'])) {
                continue;
            }
            $out['files'][] = array(
                'label' => (string) $job['label'],
                'kind'  => 'image',
                'url'   => (string) $job['url'],
            );
        }
        $out['status'] = 'completed';
        $out['failed_count'] = $failed;
        if ($failed > 0) {
            $out['message'] = sprintf('Не вышло кадров: %d — их стоимость вернулась на баланс', $failed);
        }
        return $out;
    }

    public static function fetch_task($id, $task_id) {
        $out = array('ok' => false, 'status' => 'pending', 'files' => array(), 'text' => '', 'message' => '');

        if (class_exists('GS_Manual') && GS_Manual::is_own_task($task_id)) {
            return GS_Manual::state($task_id);
        }

        if (class_exists('GS_MusicAI') && GS_MusicAI::is_own_task($task_id)) {
            return GS_MusicAI::fetch_job($id, $task_id);
        }

        // Подборка: под одним номером лежит несколько задач поставщика.
        // Готовой считаем, когда все они доиграли — иначе человек увидит
        // два кадра из пяти и решит, что остальные потерялись.
        if (strpos($task_id, 'photoset-') === 0) {
            return self::photoset_state($task_id);
        }

        if ($id === 'stt') {
            $state = GS_Transcribe::state($task_id);
            $out['ok']      = true;
            $out['status']  = (string) $state['status'];
            $out['files']   = is_array($state['files']) ? $state['files'] : array();
            $out['text']    = (string) $state['text'];
            $out['message'] = (string) $state['message'];
            return $out;
        }

        if ($id === 'ytaudio') {
            $saved = get_transient('gs_lab_yta_' . $task_id);
            $out['ok'] = true;
            if (!is_array($saved) || empty($saved['url'])) {
                $out['status'] = 'failed';
                $out['message'] = 'Дорожка не найдена — попробуйте ещё раз';
                return $out;
            }
            $out['status'] = 'completed';
            $out['files'][] = array(
                'label' => (string) $saved['title'],
                'url'   => (string) $saved['url'],
                'kind'  => 'audio',
            );
            return $out;
        }

        if ($id === 'dub') {
            return self::dub_state($task_id);
        }

        if ($id === 'music') {
            $res = self::get_json(self::API_MUSIC_INFO, array('taskId' => $task_id));
            if (!$res['ok']) {
                $out['message'] = $res['message'];
                return $out;
            }
            $data = is_array($res['body']['data']) ? $res['body']['data'] : array();
            $out['ok'] = true;
            $status = (string) ($data['status'] ?? '');

            if (in_array($status, array('CREATE_TASK_FAILED', 'GENERATE_AUDIO_FAILED', 'CALLBACK_EXCEPTION', 'SENSITIVE_WORD_ERROR'), true)) {
                $out['status'] = 'failed';
                $out['message'] = $status === 'SENSITIVE_WORD_ERROR'
                    ? 'Описание не прошло проверку — переформулируйте запрос'
                    : 'Не удалось создать трек';
                return $out;
            }

            $items = array();
            if (!empty($data['response']['sunoData']) && is_array($data['response']['sunoData'])) {
                $items = $data['response']['sunoData'];
            }
            // Поставщик отдаёт первый вариант раньше второго: показываем готовое
            // только когда пришли оба и у них есть окончательные ссылки.
            $files = array();
            foreach ($items as $index => $item) {
                $url = '';
                foreach (array('audioUrl', 'audio_url', 'sourceAudioUrl', 'source_audio_url') as $field) {
                    if (!empty($item[$field])) {
                        $url = (string) $item[$field];
                        break;
                    }
                }
                if ($url === '') {
                    continue;
                }
                $name = trim((string) ($item['title'] ?? ''));
                $seconds = isset($item['duration']) ? (int) round((float) $item['duration']) : 0;
                $label = ($name !== '' ? $name : 'Вариант ' . ((int) $index + 1));
                if ($seconds > 0) {
                    $label .= ' — ' . self::human_length($seconds);
                }
                $files[] = array('label' => $label, 'url' => $url, 'kind' => 'audio');
            }
            if ($status === 'SUCCESS' && $files) {
                $out['status'] = 'completed';
                $out['files'] = $files;
            }
            return $out;
        }

        if ($id === 'lyrics') {
            $res = self::get_json(self::API_LYRICS_INFO, array('taskId' => $task_id));
            if (!$res['ok']) {
                $out['message'] = $res['message'];
                return $out;
            }
            $data = isset($res['body']['data']) && is_array($res['body']['data']) ? $res['body']['data'] : array();
            $out['ok'] = true;
            $status = strtoupper((string) ($data['status'] ?? ''));

            if (in_array($status, array('CREATE_TASK_FAILED', 'GENERATE_LYRICS_FAILED', 'CALLBACK_EXCEPTION', 'SENSITIVE_WORD_ERROR'), true)) {
                $out['status'] = 'failed';
                $out['message'] = $status === 'SENSITIVE_WORD_ERROR'
                    ? 'Описание не прошло проверку — переформулируйте запрос'
                    : 'Не удалось написать текст';
                return $out;
            }

            $items = array();
            if (!empty($data['response']['data']) && is_array($data['response']['data'])) {
                $items = $data['response']['data'];
            }
            // Вариантов приходит два. Склеиваем их в один текст с
            // подписями: раздельные поля здесь только мешали бы копировать.
            $parts = array();
            foreach ($items as $index => $item) {
                $text = trim((string) ($item['text'] ?? ''));
                if ($text === '') {
                    continue;
                }
                $title = trim((string) ($item['title'] ?? ''));
                $head = 'Вариант ' . ((int) $index + 1) . ($title !== '' ? ' — ' . $title : '');
                $parts[] = $head . "\n\n" . $text;
            }
            if ($status === 'SUCCESS' && $parts) {
                $out['status'] = 'completed';
                $out['text'] = implode("\n\n\n", $parts);
            }
            return $out;
        }

        if ($id === 'vocal' || $id === 'denoise') {
            $res = self::get_json(self::API_VOCAL_INFO, array('taskId' => $task_id));
            if (!$res['ok']) {
                $out['message'] = $res['message'];
                return $out;
            }
            $data = $res['body']['data'];
            $flag = (string) ($data['successFlag'] ?? '');
            $out['ok'] = true;

            if (in_array($flag, array('CREATE_TASK_FAILED', 'GENERATE_AUDIO_FAILED', 'CALLBACK_EXCEPTION'), true)) {
                $out['status'] = 'failed';
                $out['message'] = $id === 'denoise'
                    ? 'Не удалось очистить запись'
                    : 'Не удалось разделить дорожки';
                return $out;
            }
            $resp = isset($data['response']) && is_array($data['response']) ? $data['response'] : array();
            if (!empty($resp['instrumentalUrl']) || !empty($resp['vocalUrl'])) {
                $out['status'] = 'completed';
                if ($id === 'denoise') {
                    // Пришедший за чистым голосом не должен разбираться, какой
                    // из двух файлов ему нужен: отдаём один, и тот самый.
                    if (!empty($resp['vocalUrl'])) {
                        $out['files'][] = array('label' => 'Чистый голос', 'url' => (string) $resp['vocalUrl'], 'kind' => 'audio');
                    }
                    return $out;
                }
                if (!empty($resp['instrumentalUrl'])) {
                    $out['files'][] = array('label' => 'Минусовка (инструментал)', 'url' => (string) $resp['instrumentalUrl'], 'kind' => 'audio');
                }
                if (!empty($resp['vocalUrl'])) {
                    $out['files'][] = array('label' => 'Вокал без музыки', 'url' => (string) $resp['vocalUrl'], 'kind' => 'audio');
                }
            }
            return $out;
        }

        $res = self::get_json(self::API_JOBS_INFO, array('taskId' => $task_id));
        if (!$res['ok']) {
            $out['message'] = $res['message'];
            return $out;
        }
        $data = $res['body']['data'];
        $out['ok'] = true;
        $state = (string) ($data['state'] ?? 'waiting');

        if ($state === 'fail') {
            $out['status'] = 'failed';
            $out['message'] = (string) ($data['failMsg'] ?? 'Генерация не удалась');
            return $out;
        }
        if ($state !== 'success') {
            return $out;
        }

        $result = isset($data['resultJson']) ? $data['resultJson'] : array();
        if (is_string($result)) {
            $decoded = json_decode($result, true);
            $result = is_array($decoded) ? $decoded : array();
        }
        $urls = array();
        if (!empty($result['resultUrls'])) {
            $urls = is_array($result['resultUrls']) ? $result['resultUrls'] : array($result['resultUrls']);
        }
        if (empty($urls)) {
            return $out;
        }

        $service = self::get_service($id);
        // Раньше здесь было «видео или звук»: третьего вида не существовало.
        // С обложкой он появился, и разбор по двум веткам молча отдавал бы
        // картинку как аудиодорожку.
        $kinds = array(
            'video' => array('video', 'Готовое видео'),
            'image' => array('image', 'Готовая картинка'),
        );
        $result_kind = $service ? (string) $service['result_kind'] : 'audio';
        list($kind, $label) = isset($kinds[$result_kind])
            ? $kinds[$result_kind]
            : array('audio', 'Очищенная запись');
        foreach ($urls as $url) {
            $out['files'][] = array('label' => $label, 'url' => (string) $url, 'kind' => $kind);
        }
        $out['status'] = 'completed';
        return $out;
    }

    /**
     * Перевод реплики перед озвучкой.
     *
     * Синхронный: занимает секунды, а отдельный этап — это ещё одно место,
     * где задача может застрять. Пустой язык означает «оставить как есть».
     *
     * @return string перевод, исходный текст или пустая строка при отказе
     */
    private static function dub_translate($speech, $lang) {
        $names = array('en' => 'английский', 'es' => 'испанский', 'de' => 'немецкий',
                       'fr' => 'французский', 'zh' => 'китайский', 'ru' => 'русский');
        if (!isset($names[$lang])) {
            return $speech;
        }
        $res = GS_Provider::chat(
            'Ты переводишь реплики для дубляжа видео. Отвечаешь только переводом, без '
            . 'пояснений и кавычек. Держишь длину близкой к оригиналу: перевод читают '
            . 'вслух поверх того же ролика.',
            'Переведи на ' . $names[$lang] . " язык:\n\n" . $speech,
            array('temperature' => 0.3, 'max_tokens' => 2000, 'timeout' => 120)
        );
        if (empty($res['ok'])) {
            return '';
        }
        $out = trim((string) $res['content']);
        return $out !== '' ? $out : '';
    }

    /**
     * Состояние дубляжа: распознавание, озвучка, артикуляция.
     *
     * Три захода к поставщику подряд, а номер задачи для страницы один.
     * Переход между ними делается здесь же, при очередном опросе: своей
     * фоновой очереди у сайта нет, а держать её ради двух шагов — лишняя
     * машинерия, которая ломается тише, чем работает.
     */
    private static function dub_state($task_id) {
        $out = array('ok' => true, 'status' => 'pending', 'files' => array(), 'text' => '', 'message' => '');
        $key = 'gs_lab_dub_' . $task_id;
        $row = get_transient($key);
        if (!is_array($row) || empty($row['stage'])) {
            $out['status'] = 'failed';
            $out['message'] = 'Задача не найдена — попробуйте ещё раз';
            return $out;
        }

        if ($row['stage'] === 'stt') {
            $state = GS_Transcribe::state((string) $row['stt_task']);
            $status = (string) $state['status'];
            if ($status === 'failed') {
                $out['status'] = 'failed';
                $out['message'] = (string) ($state['message'] ?: 'Не удалось разобрать речь в ролике');
                return $out;
            }
            if ($status !== 'completed') {
                return $out;
            }

            $speech = trim((string) $state['text']);
            if ($speech === '') {
                $out['status'] = 'failed';
                $out['message'] = 'В ролике не нашлось разборчивой речи — вставьте текст вручную';
                return $out;
            }
            $speech = self::dub_translate($speech, (string) $row['lang']);
            if ($speech === '') {
                $out['status'] = 'failed';
                $out['message'] = 'Не удалось перевести распознанную речь — попробуйте ещё раз';
                return $out;
            }

            $voiced = GS_Tts_Fallback::create_task($speech, '');
            if (empty($voiced['ok'])) {
                $out['status'] = 'failed';
                $out['message'] = (string) ($voiced['message'] ?: 'Озвучка сейчас недоступна');
                return $out;
            }
            $row['stage'] = 'tts';
            $row['tts_task'] = (string) $voiced['task_id'];
            $row['text'] = $speech;
            set_transient($key, $row, DAY_IN_SECONDS);
            return $out;
        }

        if ($row['stage'] === 'tts') {
            $res = self::get_json(self::API_JOBS_INFO, array('taskId' => (string) $row['tts_task']));
            if (!$res['ok']) {
                $out['message'] = $res['message'];
                return $out;
            }
            $data = is_array($res['body']['data']) ? $res['body']['data'] : array();
            $state = (string) ($data['state'] ?? 'waiting');
            if ($state === 'fail') {
                $out['status'] = 'failed';
                $out['message'] = 'Не удалось озвучить текст — деньги вернулись на баланс';
                return $out;
            }
            if ($state !== 'success') {
                return $out;
            }

            $result = isset($data['resultJson']) ? $data['resultJson'] : array();
            if (is_string($result)) {
                $decoded = json_decode($result, true);
                $result = is_array($decoded) ? $decoded : array();
            }
            $audio = '';
            if (!empty($result['resultUrls'])) {
                $urls = is_array($result['resultUrls']) ? $result['resultUrls'] : array($result['resultUrls']);
                $audio = (string) reset($urls);
            }
            if ($audio === '') {
                $out['status'] = 'failed';
                $out['message'] = 'Озвучка вернулась пустой — попробуйте ещё раз';
                return $out;
            }

            $created = self::post_json(self::API_JOBS, array(
                'model' => 'volcengine/video-to-video-lip-sync',
                'input' => array(
                    'video_url' => (string) $row['video_url'],
                    'audio_url' => $audio,
                    'mode'      => 'lite',
                ),
            ));
            $lip = $created['ok'] ? (string) ($created['body']['data']['taskId'] ?? '') : '';
            if ($lip === '') {
                $out['status'] = 'failed';
                $out['message'] = $created['message'] ?: 'Не удалось подогнать артикуляцию';
                return $out;
            }
            $row['stage'] = 'lip';
            $row['lip_task'] = $lip;
            $row['audio_url'] = $audio;
            set_transient($key, $row, DAY_IN_SECONDS);
            return $out;
        }

        $res = self::get_json(self::API_JOBS_INFO, array('taskId' => (string) $row['lip_task']));
        if (!$res['ok']) {
            $out['message'] = $res['message'];
            return $out;
        }
        $data = is_array($res['body']['data']) ? $res['body']['data'] : array();
        $state = (string) ($data['state'] ?? 'waiting');
        if ($state === 'fail') {
            $out['status'] = 'failed';
            $out['message'] = (string) ($data['failMsg'] ?? 'Не удалось подогнать артикуляцию');
            return $out;
        }
        if ($state !== 'success') {
            return $out;
        }

        $result = isset($data['resultJson']) ? $data['resultJson'] : array();
        if (is_string($result)) {
            $decoded = json_decode($result, true);
            $result = is_array($decoded) ? $decoded : array();
        }
        $urls = array();
        if (!empty($result['resultUrls'])) {
            $urls = is_array($result['resultUrls']) ? $result['resultUrls'] : array($result['resultUrls']);
        }
        if (empty($urls)) {
            return $out;
        }
        foreach ($urls as $url) {
            $out['files'][] = array('label' => 'Видео с новой озвучкой', 'url' => (string) $url, 'kind' => 'video');
        }
        // Дорожку отдаём тоже: её часто хотят отдельно — подложить в монтаж
        // или переозвучить другой ролик тем же голосом.
        if (!empty($row['audio_url'])) {
            $out['files'][] = array('label' => 'Только новая озвучка', 'url' => (string) $row['audio_url'], 'kind' => 'audio');
        }
        $out['status'] = 'completed';
        return $out;
    }

    /**
     * Разбор форматов запроса на разделение дорожек: документация поставщика
     * противоречива, поэтому пробуем варианты и смотрим на живой ответ.
     */
    public static function vocal_probe($audio_url, $variant = 1) {
        $callback = add_query_arg('token', GS_SFX::callback_token(), rest_url(GS_Rest::NS . '/lab/callback'));

        $payloads = array(
            1 => array('audioUrl' => $audio_url, 'type' => 'separate_vocal', 'callBackUrl' => $callback),
            2 => array('audioUrl' => $audio_url, 'type' => 'separate_vocal', 'stemName' => 'Vocals', 'callBackUrl' => $callback),
            3 => array('uploadUrl' => $audio_url, 'type' => 'separate_vocal', 'callBackUrl' => $callback),
            4 => array('audioUrl' => $audio_url, 'type' => 'split_stem', 'stemName' => 'Vocals', 'callBackUrl' => $callback),
        );
        // Вариант 0 — не постановка задачи, а сырой ответ о её состоянии:
        // по нему видно настоящую причину отказа, а не нашу трактовку.
        if ($variant === 0) {
            $key = self::api_key();
            $response = wp_remote_get(
                add_query_arg('taskId', $audio_url, self::API_VOCAL_INFO),
                array('timeout' => 45, 'headers' => array('Authorization' => 'Bearer ' . $key))
            );
            if (is_wp_error($response)) {
                return array('variant' => 0, 'ok' => false, 'message' => $response->get_error_message(), 'body' => array());
            }
            return array(
                'variant' => 0,
                'ok'      => true,
                'http'    => (int) wp_remote_retrieve_response_code($response),
                'raw'     => mb_substr((string) wp_remote_retrieve_body($response), 0, 1500),
            );
        }

        $payload = isset($payloads[$variant]) ? $payloads[$variant] : $payloads[1];

        $res = self::post_json(self::API_VOCAL, $payload);
        return array(
            'variant' => $variant,
            'sent'    => array_keys($payload),
            'ok'      => !empty($res['ok']),
            'message' => (string) $res['message'],
            'body'    => $res['body'],
        );
    }

    /**
     * Остаток кредитов у поставщика — без этого нельзя считать себестоимость
     * операции и осмысленно назначать цену для пользователя.
     *
     * @return array{ok:bool,credits:float,message:string}
     */
    public static function provider_credits() {
        $res = self::get_json('https://api.kie.ai/api/v1/chat/credit', array());
        if (empty($res['ok'])) {
            return array('ok' => false, 'credits' => 0.0, 'message' => $res['message']);
        }
        $data = $res['body']['data'];
        $credits = is_array($data) ? (float) ($data['credit'] ?? $data['credits'] ?? 0) : (float) $data;
        return array('ok' => true, 'credits' => $credits, 'message' => '');
    }

    /**
     * Сколько кредитов реально съела задача — из этого считается себестоимость.
     *
     * @return array{ok:bool,credits:float,state:string,message:string}
     */
    public static function task_credits($task_id) {
        $res = self::get_json(self::API_JOBS_INFO, array('taskId' => (string) $task_id));
        if (empty($res['ok'])) {
            return array('ok' => false, 'credits' => 0.0, 'state' => '', 'message' => $res['message']);
        }
        $data = is_array($res['body']['data']) ? $res['body']['data'] : array();
        $credits = 0.0;
        foreach (array('creditsConsumed', 'credits_consumed', 'costCredits', 'credits') as $field) {
            if (isset($data[$field])) {
                $credits = (float) $data[$field];
                break;
            }
        }
        return array(
            'ok'      => true,
            'credits' => $credits,
            'state'   => (string) ($data['state'] ?? ''),
            'message' => '',
        );
    }

    /**
     * Расширение файла по типу содержимого, с запасным вариантом по виду задачи.
     */
    private static function ext_from_type($content_type, $kind) {
        $map = array(
            'image/png'  => 'png',
            'image/jpeg' => 'jpg',
            'image/webp' => 'webp',
            'video/mp4'  => 'mp4',
            'audio/mpeg' => 'mp3',
            'audio/wav'  => 'wav',
            'audio/x-wav'=> 'wav',
            'audio/ogg'  => 'ogg',
            'audio/mp4'  => 'm4a',
        );
        $type = strtolower(trim(explode(';', (string) $content_type)[0]));
        if (isset($map[$type])) {
            return $map[$type];
        }
        if ($kind === 'video') {
            return 'mp4';
        }
        return $kind === 'image' ? 'png' : 'mp3';
    }

    /**
     * Копируем результат к себе: ссылки агрегатора живут ограниченное время.
     */
    public static function store_result($task_id, $url, $kind) {
        $task_id = preg_replace('~[^a-zA-Z0-9_-]~', '', (string) $task_id);
        if ($task_id === '' || $url === '') {
            return '';
        }
        // Файл уже лежит у нас (например, приложен вручную) — копировать нечего.
        if (strpos((string) $url, GS_Storage::generated_url()) === 0) {
            return (string) $url;
        }
        GS_Storage::ensure_dirs();

        $known = array('mp3', 'wav', 'mp4', 'ogg', 'm4a', 'png', 'jpg', 'jpeg', 'webp');
        $ext = strtolower((string) pathinfo(wp_parse_url($url, PHP_URL_PATH), PATHINFO_EXTENSION));
        if (!in_array($ext, $known, true)) {
            $ext = '';
        }

        // Имя уже известно — отдаём готовый файл, не скачивая заново.
        if ($ext !== '') {
            $name = $task_id . '-' . substr(md5($url), 0, 8) . '.' . $ext;
            $target = GS_Storage::generated_dir() . '/' . $name;
            if (file_exists($target) && filesize($target) > 1024) {
                return GS_Storage::generated_url() . '/' . $name;
            }
        }

        $response = wp_remote_get($url, array('timeout' => 180));
        if (is_wp_error($response) || (int) wp_remote_retrieve_response_code($response) !== 200) {
            return '';
        }
        $body = wp_remote_retrieve_body($response);

        // Ссылки моделей часто без расширения: тип берём из ответа,
        // иначе картинка ляжет на диск как mp3 и не откроется у клиента.
        if ($ext === '') {
            $ext = self::ext_from_type((string) wp_remote_retrieve_header($response, 'content-type'), $kind);
        }
        $name = $task_id . '-' . substr(md5($url), 0, 8) . '.' . $ext;
        $target = GS_Storage::generated_dir() . '/' . $name;
        if (file_exists($target) && filesize($target) > 1024) {
            return GS_Storage::generated_url() . '/' . $name;
        }
        if (strlen((string) $body) < 1024) {
            return '';
        }
        if (!GS_Storage::atomic_put($target, $body)) {
            return '';
        }
        return GS_Storage::generated_url() . '/' . $name;
    }
